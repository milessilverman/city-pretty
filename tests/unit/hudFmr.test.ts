import { describe, it, expect } from "vitest";
import fs from "fs";
import path from "path";

const root = path.resolve(__dirname, "../..");
const rows: any[] = JSON.parse(fs.readFileSync(path.join(root, "app/data/hud_fair_market_rents.json"), "utf-8"));
const manifest: any[] = JSON.parse(fs.readFileSync(path.join(root, "counties/manifest.json"), "utf-8")).counties;
const FIELDS = ["zero_bed_eff", "one_bed_1br", "two_bed_2br", "three_bed_3br", "four_bed_4br"];

describe("HUD Fair Market Rents (generated by scripts/fetch_hud_fmr.mjs)", () => {
  it("has a row for every manifest county, each with rents or an explicit null_reason", () => {
    const byFips = new Map(rows.map((r) => [r.fips, r]));
    expect(byFips.size).toBe(rows.length); // no duplicate fips
    for (const m of manifest) {
      const r = byFips.get(m.fips);
      expect(r, `missing row for ${m.fips} ${m.name}`).toBeDefined();
      const allNull = FIELDS.every((f) => r[f] === null);
      const allSet = FIELDS.every((f) => r[f] !== null);
      expect(allNull || allSet, `${m.fips} has partially null rents`).toBe(true);
      if (allNull) expect(typeof r.null_reason === "string" && r.null_reason.length > 10, `${m.fips} needs null_reason`).toBe(true);
    }
  });

  it("keeps the record schema and uses the exact API URL as source", () => {
    for (const r of rows) {
      expect(r.fips).toMatch(/^\d{5}$/);
      expect(r.state_code).toMatch(/^[A-Z]{2}$/);
      expect(typeof r.small_area).toBe("boolean");
      expect(r.fiscal_year).toBeGreaterThanOrEqual(2026);
      expect(r.source_agency).toContain("HUD");
      expect(r.last_verified).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      expect(r.retrieved).toMatch(/^\d{4}-\d{2}-\d{2}$/);
      if (r.one_bed_1br !== null) {
        expect(r.source_url).toBe(`https://www.huduser.gov/hudapi/public/fmr/data/${r.source_url.split("/data/")[1]}`);
        expect(r.source_url).toMatch(/\/fmr\/data\/\d{10}\?year=\d{4}$/);
        expect(r.source_url.endsWith(`year=${r.fiscal_year}`)).toBe(true);
        expect(r.metro_or_county_name).toBeTruthy();
      }
    }
  });

  it("rents are positive integers and non-decreasing by bedroom count", () => {
    let checked = 0;
    for (const r of rows) {
      if (r.one_bed_1br === null) continue;
      const v = FIELDS.map((f) => r[f]);
      for (const x of v) {
        expect(Number.isInteger(x) && x > 0, `${r.fips} ${x}`).toBe(true);
      }
      for (let i = 1; i < v.length; i++) expect(v[i], `${r.fips} bedroom ${i}`).toBeGreaterThanOrEqual(v[i - 1]);
      checked++;
    }
    expect(checked).toBeGreaterThan(500);
  });

  it("Los Angeles County 1BR equals the committed raw API response", () => {
    const raw = JSON.parse(fs.readFileSync(path.join(root, "tests/fixtures/hud_fmr_06037.json"), "utf-8"));
    const area = raw.data.basicdata.find((r: any) => r.zip_code === "MSA level");
    const la = rows.find((r) => r.fips === "06037");
    expect(la.one_bed_1br).toBe(area["One-Bedroom"]);
    expect(la.zero_bed_eff).toBe(area["Efficiency"]);
    expect(la.two_bed_2br).toBe(area["Two-Bedroom"]);
    expect(la.three_bed_3br).toBe(area["Three-Bedroom"]);
    expect(la.four_bed_4br).toBe(area["Four-Bedroom"]);
    expect(la.fiscal_year).toBe(Number(raw.data.year));
    expect(la.small_area).toBe(true);
  });

  it("Small Area FMR files are {zip: [eff,1br,2br,3br,4br]} with valid values", () => {
    const dir = path.join(root, "app/data/hud_safmr");
    const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json"));
    expect(files.length).toBeGreaterThan(0);
    for (const f of files) {
      const fips = f.replace(".json", "");
      const row = rows.find((r) => r.fips === fips);
      expect(row?.small_area, `${f} has no small_area row`).toBe(true);
      const z = JSON.parse(fs.readFileSync(path.join(dir, f), "utf-8"));
      for (const [zip, v] of Object.entries<any>(z)) {
        expect(zip).toMatch(/^\d{5}$/);
        expect(v).toHaveLength(5);
        v.forEach((x: number, i: number) => {
          expect(Number.isInteger(x) && x > 0).toBe(true);
          if (i) expect(x).toBeGreaterThanOrEqual(v[i - 1]);
        });
      }
    }
  });
});
